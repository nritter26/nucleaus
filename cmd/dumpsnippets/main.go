// Command dumpsnippets migrates the markdown snippet vault into a SQL dump
// ready for the prod SQLite database. Each markdown section becomes one
// snippet row (title + serialized markdown body), bucketed under a language
// label. The dump is idempotent: labels use INSERT OR IGNORE and the whole
// file is wrapped in one transaction.
//
// Usage:
//
//	go run ./cmd/dumpsnippets -dir docs/snippets/backup -out docs/db/snippets_seed.sql
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"nucleaus/internal/web"
)

func main() {
	dir := flag.String("dir", "docs/snippets/backup", "directory holding the markdown snippet vault")
	out := flag.String("out", "docs/db/snippets_seed.sql", "output SQL dump path")
	flag.Parse()

	entries, err := os.ReadDir(*dir)
	if err != nil {
		log.Fatalf("read %s: %v", *dir, err)
	}

	var files []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".md") {
			files = append(files, e.Name())
		}
	}
	sort.Strings(files)
	if len(files) == 0 {
		log.Fatalf("no markdown files in %s", *dir)
	}

	var b strings.Builder
	b.WriteString("-- Snippet vault migration dump (generated by cmd/dumpsnippets).\n")
	b.WriteString("-- Import into the prod SQLite database; safe to run repeatedly.\n")
	b.WriteString("BEGIN TRANSACTION;\n\n")
	for _, lang := range languageLabels() {
		fmt.Fprintf(&b, "INSERT OR IGNORE INTO labels (name, slug) VALUES ('%s', '%s');\n", lang.name, lang.slug)
	}
	b.WriteString("\n")

	used := map[string]string{} // source slug -> file
	for _, name := range files {
		raw, err := os.ReadFile(filepath.Join(*dir, name))
		if err != nil {
			log.Fatalf("read %s: %v", name, err)
		}
		doc := web.ParseDoc(string(raw))
		source := fileSlug(name)
		if prev, dup := used[source]; dup {
			log.Fatalf("source slug %q collides between %s and %s", source, prev, name)
		}
		used[source] = name
		lang := bucketFor(name)

		written := 0
		for _, sec := range doc.Sections {
			body := serialize(sec.Blocks)
			if strings.TrimSpace(body) == "" {
				continue
			}
			fmt.Fprintf(&b, "INSERT INTO snippets (title, code, notes, lang, label_id, source, created_at, updated_at)\n")
			fmt.Fprintf(&b, "VALUES (%s, %s, '', %s, (SELECT id FROM labels WHERE slug = '%s'), %s, datetime('now'), datetime('now'));\n",
				q(sec.Heading), q("## "+sec.Heading+"\n\n"+body), q(lang), lang, q(source))
			written++
		}
		log.Printf("%s -> %d snippets (label %s)", name, written, lang)
	}

	b.WriteString("\nCOMMIT;\n")

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		log.Fatalf("create output dir: %v", err)
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatalf("write %s: %v", *out, err)
	}
	log.Printf("wrote %s", *out)
}

func q(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func fileSlug(name string) string {
	base := strings.TrimSuffix(name, ".md")
	base = strings.TrimPrefix(base, "100_")
	return strings.ReplaceAll(base, "_", "-")
}

func bucketFor(filename string) string {
	base := strings.ToLower(fileSlug(filename))
	switch {
	case strings.Contains(base, "postgres"), strings.Contains(base, "pg-"):
		return "postgres"
	case strings.HasPrefix(base, "golang"), strings.HasPrefix(base, "go-"), strings.HasPrefix(base, "go_"), base == "go":
		return "golang"
	case strings.HasPrefix(base, "typescript"), strings.HasPrefix(base, "ts-"):
		return "typescript"
	case strings.HasPrefix(base, "bash"), strings.HasPrefix(base, "shell"):
		return "bash"
	case strings.HasPrefix(base, "docker"), strings.HasPrefix(base, "compose"):
		return "docker"
	case strings.HasPrefix(base, "rust"):
		return "rust"
	}
	return "golang"
}

func languageLabels() []struct{ slug, name string } {
	return []struct{ slug, name string }{
		{"golang", "Golang"},
		{"typescript", "TypeScript"},
		{"bash", "Bash"},
		{"docker", "Docker"},
		{"postgres", "Postgres"},
		{"rust", "Rust"},
	}
}

// serialize turns parsed blocks back into markdown that parseMarkdown can
// render identically.
func serialize(blocks []web.MdBlock) string {
	var b strings.Builder
	for i, blk := range blocks {
		if i > 0 {
			b.WriteString("\n")
		}
		switch blk.Kind {
		case "p":
			b.WriteString(blk.Text)
			b.WriteString("\n")
		case "quote":
			b.WriteString("> ")
			b.WriteString(blk.Text)
			b.WriteString("\n")
		case "list":
			for _, item := range blk.Items {
				fmt.Fprintf(&b, "- %s\n", item.Text)
				for _, child := range item.Children {
					fmt.Fprintf(&b, "  - %s\n", child)
				}
			}
		case "olist":
			for n, item := range blk.Items {
				fmt.Fprintf(&b, "%d. %s\n", n+1, item.Text)
				for _, child := range item.Children {
					fmt.Fprintf(&b, "   - %s\n", child)
				}
			}
		case "table":
			for r, row := range blk.Rows {
				b.WriteString("| " + strings.Join(row, " | ") + " |\n")
				if r == 0 {
					cells := make([]string, len(row))
					for j := range cells {
						cells[j] = "---"
					}
					b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
				}
			}
		case "code":
			lang := blk.Lang
			fmt.Fprintf(&b, "```%s\n%s\n```\n", lang, blk.Body)
		case "head":
			b.WriteString("### ")
			b.WriteString(blk.Text)
			b.WriteString("\n")
		}
	}
	return b.String()
}
